"""
ponytail — «ленивый сеньор» для код-агентов команды (skill DietrichGebert/ponytail).

Плагином в Python-агента skill не поставить, поэтому его правила вшиваются в
системный промпт код-воркеров через apply(). Тот же decision-ladder лежит в
корневом AGENTS.md (его читают кодинг-CLI: Claude Code / Codex / Hermes) — здесь
единственная Python-копия. Применять ТОЛЬКО к задачам про код: на не-код задачах
(текст/дизайн/ресёрч/письма) ponytail вреден и не подключается.

Использование:
    import ponytail
    goal = ponytail.apply("Ты решаешь код-задачи ...")
"""

# Decision-ladder ponytail (verbatim). Держим синхронно с корневым AGENTS.md.
RULES = """
Работай как ленивый сеньор: лениво = эффективно, не небрежно. Лучший код — не написанный.
Перед тем как писать код, остановись на первой подходящей ступени:
1. Это вообще надо строить? (YAGNI)
2. Это уже есть в кодовой базе? Переиспользуй хелпер/утилиту/паттерн, не переписывай.
3. Это уже умеет стандартная библиотека? Используй её.
4. Это покрывает нативная фича платформы? Используй её.
5. Это решает уже установленная зависимость? Используй её.
6. Это можно одной строкой? Сделай одной строкой.
7. Только потом: минимальный код, который работает.

Правила: никаких незапрошенных абстракций, новых зависимостей и boilerplate.
Удаление важнее добавления, скучное важнее умного, меньше файлов. Побеждает
кратчайший работающий diff — но только после того, как понял задачу. Осознанные
упрощения помечай комментарием `ponytail:` с указанием потолка и пути апгрейда.

НЕ ленись в: понимании задачи (сначала прочитай и проследи реальный поток),
валидации на границах доверия, обработке ошибок против потери данных, безопасности.
Нетривиальная логика оставляет ОДНУ запускаемую проверку (assert-демо или маленький
тест, без фреймворков). Тривиальные однострочники теста не требуют.
""".strip()


def apply(goal: str, level: str = "full") -> str:
    """Добавить правила ponytail к goal код-агента. level='off' → goal без изменений
    (чтобы можно было выключить через конфиг, не трогая вызовы)."""
    if level == "off":
        return goal
    return f"{goal}\n\n=== PONYTAIL ({level}) ===\n{RULES}"
